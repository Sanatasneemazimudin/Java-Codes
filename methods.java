public class methods {
    static int add(int a, int b) {
        return a + b;
    }
    static int multiply(int a, int b) {
        return a * b;
    }
    public static void main(String[] args) {
        System.out.println("Sum: " + add(10, 20));
        System.out.println("Product: "
                + multiply(5, 4));
    }
}